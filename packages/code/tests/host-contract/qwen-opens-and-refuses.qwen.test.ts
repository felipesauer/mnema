/**
 * QWEN CODE OPENS WITH THE RECORD AND REFUSES THE WRITE, in the real Qwen Code with the Claude Code
 * plugin of this tree installed as an extension: the opening is in the system instruction of
 * the first request, the server's tools are offered, a write under a rule that refuses is not made and
 * the model is handed the rule, for `write_file` and for `edit`, and a rule that only asks for a
 * person is let through, because the command the plugin ships for this host answers a refusal and
 * nothing else.
 *
 * WHAT IS HELD HERE AND WHAT IS NOT. The product's half (what `mnema before-a-write --host qwen`
 * answers, and what `mnema brief --hook` prints) is `a-rule-that-refuses-a-write.test.ts` and the
 * brief's own cases. What Qwen Code does with them is the host's, read here off the requests it
 * sends a stand-in for the model and off the file that was or was not written.
 * NOT HELD: that the model reads what arrived; a ceiling Qwen Code may put on the opening; the
 * handler's behaviour when `mnema` outlasts its 15 seconds; an interactive session, where the host
 * turns an `ask` into a question to the person; a subagent's hooks; and any file a shell command
 * writes.
 */

import { existsSync, mkdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import {
  aQwenForEachCase,
  replacing,
  theResultOfTheCall,
  theSystemTextsOf,
  theToolsOf,
  writing,
} from './support/the-qwen.js';
import {
  aFile,
  aLineTheReaderRefuses,
  decide,
  ruleAt,
  theChannelFactsOf,
  theSegmentOf,
} from './support/the-record-to-stand-on.js';

describe('qwen code opens with the record and refuses the write', () => {
  const start = aQwenForEachCase();

  it('opens with the decision in force, in the system instruction, and offers the mnema server', async () => {
    const session = await start({
      project: (project) => {
        decide(project, 'Bill in UTC');
      },
    });
    const withTools = session.requests.filter((request) => theToolsOf(request).length > 0);
    const first = withTools[0];
    if (first === undefined) throw new Error('Qwen Code never offered the model a tool');
    // The host puts what a `SessionStart` hook says in a block at the end of the SYSTEM instruction,
    // with the angle brackets of the text escaped, and not in a turn of the user's.
    const opening = theSystemTextsOf(first).filter((text) =>
      text.includes('Generated by `mnema brief`'),
    );
    expect(opening).toHaveLength(1);
    expect(opening[0]).toContain('<qwen:session-start-context hidden="true">');
    expect(opening[0]).toContain('&lt;!-- Generated by `mnema brief`');
    expect(opening[0]).toContain('Bill in UTC');
    // The host defers the server's tools: it lists them by name in the first turn and hands a
    // schema only when one is asked for, so the tool is read from the request's text.
    expect(JSON.stringify(first.body)).toContain('mcp__mnema__record_decision');
    expect(session.calls).toContain('mcp');
  }, 180_000);

  it('asks the verbs for the opening once for the session, however many requests it makes', async () => {
    const session = await start({
      project: (project) => {
        decide(project, 'Bill in UTC');
      },
      call: writing('src/billing/invoice.ts'),
    });
    expect(session.requests.length).toBeGreaterThanOrEqual(2);
    expect(session.calls.filter((call) => call === 'brief --hook')).toHaveLength(1);
    expect(session.calls.filter((call) => /^recall --hook/.test(call))).toHaveLength(1);
  }, 180_000);

  it('deny, `write_file`: the file is not created and the model reads the rule that refused it', async () => {
    let rule = '';
    const session = await start({
      project: (project) => {
        rule = ruleAt(project, 'Billing is frozen', 'src/frozen', 'refuses-a-write');
      },
      call: writing('src/frozen/invoice.ts'),
    });
    expect(existsSync(join(session.project, 'src/frozen/invoice.ts'))).toBe(false);
    const handed = theResultOfTheCall(session);
    expect(handed, 'Qwen Code never handed the model a result').toBeDefined();
    expect(handed).toContain('refuses a write at src/frozen/invoice.ts');
    expect(handed).toContain(rule);
    expect(theChannelFactsOf(session.project, session.home)).toMatchObject({
      'channel.refused': 1,
      'channel.asked': 0,
    });
  }, 180_000);

  it('deny, `edit`: the file keeps what it had', async () => {
    let file = '';
    const session = await start({
      project: (project) => {
        ruleAt(project, 'Billing is frozen', 'src/frozen', 'refuses-a-write');
        file = aFile(project, 'src/frozen/invoice.ts', 'export const total = 1;\n');
      },
      call: replacing('src/frozen/invoice.ts', 'total = 1', 'total = 2'),
    });
    expect(readFileSync(file, 'utf-8')).toBe('export const total = 1;\n');
    expect(theResultOfTheCall(session)).toContain('refuses a write at src/frozen/invoice.ts');
    expect(theChannelFactsOf(session.project, session.home)['channel.refused']).toBe(1);
  }, 180_000);

  it('a record with a line the reader refuses: a write no rule addresses is not created, and the model reads why', async () => {
    let bytes = '';
    const session = await start({
      project: (project) => {
        ruleAt(project, 'Billing is frozen', 'src/frozen', 'refuses-a-write');
        mkdirSync(join(project.dir, 'src/free'), { recursive: true });
        bytes = aLineTheReaderRefuses(project);
      },
      call: writing('src/free/notes.ts'),
    });
    expect(existsSync(join(session.project, 'src/free/notes.ts'))).toBe(false);
    const handed = theResultOfTheCall(session);
    expect(handed, 'Qwen Code never handed the model a result').toBeDefined();
    expect(handed).toContain('The write is refused');
    expect(handed).toContain('If a newer mnema wrote the line, read the record with it.');
    expect(theSegmentOf(session.project)).toBe(bytes);
  }, 180_000);

  it('fails open: with no `mnema` on the PATH the handler says nothing, and the file is created', async () => {
    const session = await start({
      project: (project) => {
        ruleAt(project, 'Billing is frozen', 'src/frozen', 'refuses-a-write');
      },
      call: writing('src/frozen/invoice.ts'),
      mnema: 'absent',
    });
    expect(existsSync(join(session.project, 'src/frozen/invoice.ts'))).toBe(true);
    expect(theChannelFactsOf(session.project, session.home)['channel.refused']).toBe(0);
  }, 180_000);

  it('a program named mnema that is not this product cannot answer: the write at a governed path is refused, and the model reads why', async () => {
    const session = await start({
      project: (project) => {
        ruleAt(project, 'Billing is frozen', 'src/frozen', 'refuses-a-write');
      },
      call: writing('src/frozen/invoice.ts'),
      mnema: 'a stranger',
    });
    expect(existsSync(join(session.project, 'src/frozen/invoice.ts'))).toBe(false);
    expect(theResultOfTheCall(session)).toContain('mnema could not answer for this write');
    // The session is told which program answered and that no record was handed to it, and no verb
    // of the stranger's ran for the opening.
    const system = session.requests.flatMap((request) => theSystemTextsOf(request)).join('\n');
    expect(system).toContain('it is not @mnema/code');
    expect(system).not.toContain('Generated by `mnema brief`');
    expect(session.calls.filter((call) => /^(brief|recall)/.test(call))).toEqual([]);
  }, 180_000);

  it('with no extension installed, the same write is created: it is the extension that refuses', async () => {
    const session = await start({
      project: (project) => {
        ruleAt(project, 'Billing is frozen', 'src/frozen', 'refuses-a-write');
      },
      call: writing('src/frozen/invoice.ts'),
      extension: false,
    });
    expect(existsSync(join(session.project, 'src/frozen/invoice.ts'))).toBe(true);
    expect(theChannelFactsOf(session.project, session.home)['channel.refused']).toBe(0);
  }, 180_000);

  it('control: a path a rule only governs is created, and the extension said nothing to stop it', async () => {
    const session = await start({
      project: (project) => {
        ruleAt(project, 'Bill in UTC', 'src/billing', 'governs');
      },
      call: writing('src/billing/invoice.ts'),
    });
    expect(existsSync(join(session.project, 'src/billing/invoice.ts'))).toBe(true);
    expect(theChannelFactsOf(session.project, session.home)).toMatchObject({
      'channel.refused': 0,
      'channel.asked': 0,
    });
  }, 180_000);

  it('ask: a rule that only asks for a person is let through, and no asking is recorded', async () => {
    const session = await start({
      project: (project) => {
        ruleAt(project, 'Ledger changes need finance', 'src/ledger', 'asks-for-a-person');
      },
      call: writing('src/ledger/entry.ts'),
    });
    expect(existsSync(join(session.project, 'src/ledger/entry.ts'))).toBe(true);
    expect(theChannelFactsOf(session.project, session.home)).toMatchObject({
      'channel.refused': 0,
      'channel.asked': 0,
    });
  }, 180_000);
});
