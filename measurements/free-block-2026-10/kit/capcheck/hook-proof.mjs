// THE PROOF THAT A HOST'S PLUGIN HOOKS RAN, read off the wire the relay recorded (no model request): the SessionStart hook of the
// pinned mnema plugin runs `mnema brief`, and the host hands its output to the model as one more message of the FIRST request.
// So, for a run with the hooks trusted and a reference run without the trust of the same host:
//   - the first request of the trusted run carries a message that starts with the header `mnema brief` writes, and the capability
//     marker inside it (the accepted decision `capcheck-7f3a` is in force in the sandbox record);
//   - the first request of the reference run carries neither, and one message fewer.
// Optionally the host's own rollout of the session says the policy it ran under (sandbox, approvals), copied here as facts.
//
//   node capcheck/hook-proof.mjs <resultsDir> <trustedRun> <referenceRun> [--rollout <file>]
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { readWireGz } from '../lib/run-common.mjs';
import { MARKER } from './criterion.mjs';

export const BRIEF_HEADER = '<!-- Generated by `mnema brief`';

const textOf = (item) => (Array.isArray(item?.content) ? item.content.map((p) => p?.text ?? '').join('') : typeof item?.content === 'string' ? item.content : '');

/** What the first model request of a run carried: how many input items, and which of them is the output of the brief hook. */
export function firstRequestFacts(wire) {
  const first = wire.find((r) => r.forwarded === true);
  const input = Array.isArray(first?.request?.input) ? first.request.input : [];
  const messages = input.map((item, index) => ({ index, role: item.role ?? item.type, text: textOf(item) }));
  const brief = messages.find((m) => m.text.startsWith(BRIEF_HEADER));
  return {
    inputItems: input.length,
    roles: messages.map((m) => m.role),
    briefHookOutput:
      brief === undefined
        ? null
        : { index: brief.index, role: brief.role, characters: brief.text.length, sha256: createHash('sha256').update(brief.text).digest('hex'), carriesMarker: brief.text.includes(MARKER) },
    markerAnywhereInFirstRequest: JSON.stringify(first?.request ?? {}).includes(MARKER),
  };
}

export function hookProof(resultsDir, trustedRun, referenceRun, rolloutFile = null) {
  const trusted = firstRequestFacts(readWireGz(join(resultsDir, trustedRun)));
  const reference = firstRequestFacts(readWireGz(join(resultsDir, referenceRun)));
  const reasons = [];
  if (trusted.briefHookOutput === null) reasons.push('the first request of the trusted run carries no output of the brief hook');
  else if (!trusted.briefHookOutput.carriesMarker) reasons.push('the hook output does not carry the capability marker');
  if (reference.briefHookOutput !== null) reasons.push('the reference run, without the trust, also carries the hook output: it proves nothing');
  if (trusted.inputItems !== reference.inputItems + 1) reasons.push(`the trusted first request has ${trusted.inputItems} items, the reference ${reference.inputItems}: expected exactly one more`);
  const proof = { hooksRan: reasons.length === 0, reasons, trusted: { run: trustedRun, ...trusted }, reference: { run: referenceRun, ...reference } };
  if (rolloutFile !== null) {
    const turn = readFileSync(rolloutFile, 'utf8')
      .split('\n')
      .filter(Boolean)
      .map((l) => JSON.parse(l))
      .find((j) => j.type === 'turn_context')?.payload;
    proof.policy_the_host_ran_under = { approval_policy: turn?.approval_policy, sandbox_policy: turn?.sandbox_policy, network_of_tools: turn?.permission_profile?.network, model: turn?.model };
  }
  writeFileSync(join(resultsDir, trustedRun, 'hook-proof.json'), `${JSON.stringify(proof, null, 2)}\n`);
  return proof;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const args = process.argv.slice(2);
  const i = args.indexOf('--rollout');
  const rollout = i >= 0 ? args.splice(i, 2)[1] : null;
  const [resultsDir, trustedRun, referenceRun] = args;
  console.log(JSON.stringify(hookProof(resultsDir, trustedRun, referenceRun, rollout), null, 2));
}
